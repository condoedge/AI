<?php

declare(strict_types=1);

namespace Condoedge\Ai\Tests\Unit\Services\Security;

use Condoedge\Ai\Services\Security\CypherScopeAnalyzer;
use Condoedge\Ai\Services\Security\Scope\FilterClause;
use Condoedge\Ai\Services\Security\Scope\NodeBinding;
use Condoedge\Ai\Services\Security\SecurityFilterInjector;
use Condoedge\Ai\Tests\TestCase;

/**
 * OPTIONAL MATCH tenant-scoping regression + security tests.
 *
 * Regression (AiQueryLog id 674, caught by the live eval harness): the injector
 * spliced a MANDATORY `MATCH (i)-[:BELONGS_TO_UNION]->(ai_sN:Union) WHERE …`
 * for the variable `i` that was bound by OPTIONAL MATCH. When no invoice
 * matches (i is null), a mandatory MATCH on the null variable eliminates ALL
 * rows — the query returned 0 rows although the unit matched (live data: 3
 * rows without the injected clauses).
 *
 * SECURITY INVARIANT pinned here: a non-null OPTIONAL variable must STILL be
 * team-scoped. The fix must express the scope null-tolerantly —
 * `(i IS NULL OR EXISTS { MATCH (i)-[:REL]->(s:Union) WHERE s.team_id IN
 * $ai_team_ids })` — never simply skip scoping for OPTIONAL variables.
 *
 * Also pinned: a MANDATORY binding's direct predicate must never be attached to
 * an OPTIONAL MATCH's own WHERE (there it only filters the optional match, so a
 * cross-tenant mandatory row would still flow through with the optional
 * variable null — a leak). It must be enforced at row level (`WITH * WHERE …`).
 */
class OptionalMatchScopingTest extends TestCase
{
    private CypherScopeAnalyzer $analyzer;
    private SecurityFilterInjector $injector;

    /**
     * The EXACT executed query from AiQueryLog id 674 as generated by the LLM
     * (already team-scoped on u1 by generation).
     */
    private const Q674 = 'MATCH (u:Unit {name: "310"})-[:UNION]->(u1:Union) WHERE u1.team_id IN $ai_team_ids '
        . 'OPTIONAL MATCH (i:Invoice) WHERE i.customer_type = "unit" AND i.customer_id = u.id AND toFloat(i.calc_due_amount) > 0 '
        . 'RETURN u.id AS unit_id, u.name AS unit_name, sum(toFloat(i.calc_due_amount)) AS balance, count(i) AS open_invoices LIMIT 100';

    public function setUp(): void
    {
        parent::setUp();
        $this->analyzer = new CypherScopeAnalyzer();
        $this->injector = new SecurityFilterInjector();
    }

    /**
     * Per-binding resolver mirroring the real TeamPathResolver output for the
     * CondoEdge labels involved: Union carries team_id directly; Unit and
     * Invoice are scoped through a relationship to a Union.
     */
    private function condoedgeFilter(): callable
    {
        return static function (NodeBinding $b): ?FilterClause {
            return match ($b->label) {
                'Unit' => new FilterClause(
                    'match',
                    "MATCH ({$b->alias})-[:UNION]->(u1:Union) WHERE u1.team_id IN \$ai_team_ids",
                    ['ai_team_ids' => [14]]
                ),
                'Invoice', 'Vehicle' => new FilterClause(
                    'match',
                    "MATCH ({$b->alias})-[:BELONGS_TO_UNION]->(u1:Union) WHERE u1.team_id IN \$ai_team_ids",
                    ['ai_team_ids' => [14]]
                ),
                default => new FilterClause(
                    'where',
                    "WHERE {$b->alias}.team_id IN \$ai_team_ids",
                    ['ai_team_ids' => [14]]
                ),
            };
        };
    }

    private function inject(string $cypher, callable $filterFor): ?string
    {
        $plan = $this->analyzer->analyze($cypher);
        return $this->injector->inject($cypher, $plan, $filterFor);
    }

    /**
     * The rewrite with every `EXISTS { … }` block removed, so "no mandatory
     * MATCH on an OPTIONAL-bound variable" can be asserted on what remains.
     */
    private function withoutExistsBlocks(string $cypher): string
    {
        return (string) preg_replace('/EXISTS\s*\{[^{}]*\}/i', '', $cypher);
    }

    // =====================================================================
    // D1 regression — the exact live query (AiQueryLog id 674)
    // =====================================================================

    /** @test */
    public function q674_no_bare_mandatory_match_on_the_optional_bound_variable(): void
    {
        $out = $this->inject(self::Q674, $this->condoedgeFilter());

        $this->assertNotNull($out, 'q674 must stay injectable (fail-closed here would block a valid query)');

        // The FATAL defect: a mandatory `MATCH (i)…` outside an EXISTS block
        // destroys OPTIONAL semantics (null i eliminates every row).
        $stripped = $this->withoutExistsBlocks($out);
        $this->assertDoesNotMatchRegularExpression(
            '/\bMATCH\s*\(\s*i\s*\)/',
            $stripped,
            "Mandatory MATCH injected on OPTIONAL-bound variable i: {$out}"
        );

        // The null-tolerant scope predicate is present instead, and it still
        // enforces $ai_team_ids on any non-null i (SECURITY INVARIANT).
        $this->assertMatchesRegularExpression(
            '/\(\s*i IS NULL OR EXISTS \{ MATCH \(i\)-\[:BELONGS_TO_UNION\]->\((ai_s\d+):Union\) WHERE \1\.team_id IN \$ai_team_ids \}\s*\)/',
            $out,
            "Null-tolerant EXISTS scope for optional i missing: {$out}"
        );

        // It must be attached to the OPTIONAL MATCH's own WHERE (AND-merged into
        // the existing predicate), so a scoped-out invoice becomes null and does
        // NOT contribute to the aggregates while the unit row survives.
        $this->assertMatchesRegularExpression(
            '/toFloat\(i\.calc_due_amount\) > 0 AND \(i IS NULL OR EXISTS \{/',
            $out,
            "EXISTS scope not merged into the OPTIONAL MATCH's WHERE: {$out}"
        );

        // The MANDATORY binding u keeps its regular relationship MATCH block.
        $this->assertMatchesRegularExpression(
            '/MATCH \(u\)-\[:UNION\]->\((ai_s\d+):Union\) WHERE \1\.team_id IN \$ai_team_ids/',
            $out,
            "Mandatory Unit relationship scope missing: {$out}"
        );

        // Original query parts intact.
        $this->assertStringContainsString('MATCH (u:Unit {name: "310"})-[:UNION]->(u1:Union) WHERE u1.team_id IN $ai_team_ids', $out);
        $this->assertStringContainsString('OPTIONAL MATCH (i:Invoice) WHERE i.customer_type = "unit"', $out);
        $this->assertStringContainsString('RETURN u.id AS unit_id', $out);

        // Bound parameter only, never inlined ids.
        $this->assertStringNotContainsString('IN [', $out);

        // Structurally valid Cypher (the runtime gate must ACCEPT the rewrite —
        // otherwise the executor safe-stops and the query silently returns no
        // rows, which is the same user-visible failure).
        $this->assertTrue(
            CypherStructuralValidator::isValid($out),
            'q674 rewrite is not structurally valid Cypher: ' . $out
                . ' | reason: ' . (CypherStructuralValidator::diagnose($out) ?? '')
        );
    }

    /** @test */
    public function q674_mandatory_direct_predicate_is_row_level_not_trapped_in_optional_where(): void
    {
        $out = $this->inject(self::Q674, $this->condoedgeFilter());

        $this->assertNotNull($out);

        // The broken shape: `… toFloat(i.calc_due_amount) > 0 AND u1.team_id IN
        // $ai_team_ids …` — u1's (mandatory) predicate AND-merged into the
        // OPTIONAL MATCH's WHERE, where it only filters the optional match and
        // does NOT constrain u1 rows.
        $this->assertDoesNotMatchRegularExpression(
            '/calc_due_amount\) > 0 AND u1\.team_id IN \$ai_team_ids/',
            $out,
            "Mandatory u1 predicate trapped inside the OPTIONAL MATCH's WHERE: {$out}"
        );

        // Instead it is enforced at row level after the optional part.
        $this->assertMatchesRegularExpression(
            '/WITH \* WHERE u1\.team_id IN \$ai_team_ids/',
            $out,
            "Mandatory u1 predicate not enforced at row level: {$out}"
        );
    }

    // =====================================================================
    // Security — non-null OPTIONAL matches must still be team-scoped
    // =====================================================================

    /** @test */
    public function optional_binding_with_direct_filter_is_scoped_null_tolerantly(): void
    {
        $directFilter = static fn(NodeBinding $b): FilterClause => new FilterClause(
            'where',
            "WHERE {$b->alias}.team_id IN \$ai_team_ids",
            ['ai_team_ids' => [1, 2]]
        );

        $out = $this->inject('MATCH (a:Account) OPTIONAL MATCH (i:Invoice) RETURN a, i', $directFilter);

        $this->assertNotNull($out);

        // The optional binding is scoped null-tolerantly ON THE OPTIONAL MATCH:
        // a cross-tenant invoice fails the match and becomes null (never
        // surfaced), a same-tenant invoice passes. The row itself survives.
        $this->assertStringContainsString(
            'OPTIONAL MATCH (i:Invoice) WHERE (i IS NULL OR i.team_id IN $ai_team_ids)',
            $out
        );

        // The MANDATORY binding a is NOT attached to the optional WHERE (that
        // would not constrain a's rows — leak). It is row-level enforced.
        $this->assertMatchesRegularExpression('/WITH \* WHERE a\.team_id IN \$ai_team_ids/', $out);
        $this->assertDoesNotMatchRegularExpression(
            '/OPTIONAL MATCH \(i:Invoice\) WHERE [^R]*\ba\.team_id/',
            $out,
            "Mandatory predicate for a trapped in the OPTIONAL MATCH's WHERE: {$out}"
        );

        $this->assertTrue(
            CypherStructuralValidator::isValid($out),
            'Rewrite not structurally valid: ' . $out
                . ' | reason: ' . (CypherStructuralValidator::diagnose($out) ?? '')
        );
    }

    /** @test */
    public function optional_binding_with_relationship_filter_is_scoped_via_exists(): void
    {
        $out = $this->inject(
            'MATCH (a:Account) OPTIONAL MATCH (v:Vehicle) RETURN a, v',
            $this->condoedgeFilter()
        );

        $this->assertNotNull($out);

        // Null-tolerant existential scope — non-null v MUST satisfy the team
        // relationship; null v (no vehicle) keeps the row.
        $this->assertMatchesRegularExpression(
            '/\(v IS NULL OR EXISTS \{ MATCH \(v\)-\[:BELONGS_TO_UNION\]->\((ai_s\d+):Union\) WHERE \1\.team_id IN \$ai_team_ids \}\)/',
            $out,
            "Null-tolerant EXISTS scope for optional v missing: {$out}"
        );

        // No mandatory MATCH on v outside the EXISTS block.
        $this->assertDoesNotMatchRegularExpression(
            '/\bMATCH\s*\(\s*v\s*\)/',
            $this->withoutExistsBlocks($out),
            "Mandatory MATCH injected on OPTIONAL-bound v: {$out}"
        );

        // Team ids stay bound.
        $this->assertStringNotContainsString('IN [', $out);

        $this->assertTrue(
            CypherStructuralValidator::isValid($out),
            'Rewrite not structurally valid: ' . $out
                . ' | reason: ' . (CypherStructuralValidator::diagnose($out) ?? '')
        );
    }

    /** @test */
    public function optional_only_query_is_scoped_null_tolerantly(): void
    {
        $directFilter = static fn(NodeBinding $b): FilterClause => new FilterClause(
            'where',
            "WHERE {$b->alias}.team_id IN \$ai_team_ids",
            ['ai_team_ids' => [1, 2]]
        );

        $out = $this->inject('OPTIONAL MATCH (i:Invoice) RETURN i', $directFilter);

        $this->assertNotNull($out);
        $this->assertStringContainsString('WHERE (i IS NULL OR i.team_id IN $ai_team_ids)', $out);
        $this->assertTrue(CypherStructuralValidator::isValid($out));
    }

    // =====================================================================
    // Behaviour for regular (non-OPTIONAL) MATCH bindings is UNCHANGED
    // =====================================================================

    /** @test */
    public function mandatory_bindings_keep_the_existing_injection_shape(): void
    {
        $out = $this->inject('MATCH (u:Unit) MATCH (i:Invoice) RETURN u, i', $this->condoedgeFilter());

        $this->assertNotNull($out);
        // Invoice is mandatory here → a regular mandatory relationship MATCH
        // block, no null-tolerance, no WITH *.
        $this->assertMatchesRegularExpression(
            '/MATCH \(i\)-\[:BELONGS_TO_UNION\]->\((ai_s\d+):Union\) WHERE \1\.team_id IN \$ai_team_ids/',
            $out
        );
        $this->assertMatchesRegularExpression(
            '/MATCH \(u\)-\[:UNION\]->\((ai_s\d+):Union\) WHERE \1\.team_id IN \$ai_team_ids/',
            $out
        );
        $this->assertStringNotContainsString('IS NULL', $out);
        $this->assertStringNotContainsString('EXISTS', $out);
        $this->assertStringNotContainsString('WITH *', $out);
        $this->assertTrue(CypherStructuralValidator::isValid($out));
    }
}
